#!/usr/bin/env python3
"""scripts/check_iodoc_sync.py is the gate of the iodoc-sync CI job: it must fail on
every kind of drift, and only on those."""
import copy
import json
import os
import subprocess
import sys
import tempfile
import unittest

SCRIPT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "scripts", "check_iodoc_sync.py")

IO_DOC = {
    "MqttInputTemp": {
        "description": "temp",
        "parameters": [
            {"name": "a", "description": "first"},
            {"name": "b", "description": "second"},
        ],
    },
    "devices": {"proxy": {"family": "climate", "command_fields": [{"name": "mode"}]}},
}
TEMPLATES = {"format": 1, "templates": [{"id": "t1", "impl": "proxy"}]}


def write(root, lang, name, doc, indent=4):
    os.makedirs(os.path.join(root, lang), exist_ok=True)
    with open(os.path.join(root, lang, name), "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=indent)


class CheckIodocSync(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.shipped = os.path.join(self._tmp.name, "shipped")
        self.server = os.path.join(self._tmp.name, "server")
        for root in (self.shipped, self.server):
            for lang in ("en", "fr"):
                write(root, lang, "io_doc.json", IO_DOC)
                write(root, lang, "device_templates.json", TEMPLATES)

    def tearDown(self):
        self._tmp.cleanup()

    def run_check(self):
        r = subprocess.run([sys.executable, "-I", SCRIPT, self.server, "--data", self.shipped],
                           capture_output=True, text=True)
        return r.returncode, r.stdout + r.stderr

    def drift(self, lang, name, mutate):
        doc = copy.deepcopy(IO_DOC if name == "io_doc.json" else TEMPLATES)
        mutate(doc)
        write(self.shipped, lang, name, doc)

    def test_identical_files_pass(self):
        rc, out = self.run_check()
        self.assertEqual(rc, 0, out)

    def test_key_order_and_formatting_do_not_matter(self):
        reordered = {k: IO_DOC[k] for k in reversed(list(IO_DOC))}
        write(self.shipped, "en", "io_doc.json", reordered, indent=None)
        rc, out = self.run_check()
        self.assertEqual(rc, 0, out)

    def test_a_changed_description_is_named(self):
        self.drift("en", "io_doc.json", lambda d: d["MqttInputTemp"]["parameters"][1].update(description="x"))
        rc, out = self.run_check()
        self.assertEqual(rc, 1, out)
        self.assertIn("en/io_doc.json.MqttInputTemp.parameters[b].description", out)

    def test_a_device_the_installer_lacks_fails(self):
        self.drift("fr", "io_doc.json", lambda d: d["devices"].pop("proxy"))
        rc, out = self.run_check()
        self.assertEqual(rc, 1, out)
        self.assertIn("devices.proxy: generated by the server, not shipped", out)

    def test_an_entry_the_server_dropped_fails(self):
        self.drift("en", "io_doc.json", lambda d: d.update(Gadspot={"description": "old"}))
        rc, out = self.run_check()
        self.assertEqual(rc, 1, out)
        self.assertIn("Gadspot: shipped, but not generated by the server", out)

    def test_the_templates_are_compared_too(self):
        self.drift("fr", "device_templates.json", lambda d: d["templates"][0].update(impl="thermostat"))
        rc, out = self.run_check()
        self.assertEqual(rc, 1, out)
        self.assertIn("fr/device_templates.json", out)

    def test_an_array_in_another_order_fails(self):
        self.drift("en", "io_doc.json", lambda d: d["MqttInputTemp"]["parameters"].reverse())
        rc, _ = self.run_check()
        self.assertEqual(rc, 1)

    def test_a_missing_file_fails(self):
        os.remove(os.path.join(self.shipped, "fr", "device_templates.json"))
        rc, out = self.run_check()
        self.assertEqual(rc, 1, out)
        self.assertIn("missing", out)

    def test_a_missing_server_file_fails(self):
        os.remove(os.path.join(self.server, "en", "io_doc.json"))
        rc, out = self.run_check()
        self.assertEqual(rc, 1, out)

    def test_a_missing_entry_is_named_by_its_name(self):
        self.drift("en", "io_doc.json", lambda d: d["MqttInputTemp"]["parameters"].pop())
        rc, out = self.run_check()
        self.assertEqual(rc, 1, out)
        self.assertIn("MqttInputTemp.parameters[b]: generated by the server, not shipped", out)

    def test_a_long_report_is_cut(self):
        def many(d):
            d["devices"] = {"impl%d" % i: {} for i in range(40)}
        self.drift("en", "io_doc.json", many)
        rc, out = self.run_check()
        self.assertEqual(rc, 1, out)
        self.assertIn("more", out)
        self.assertLess(out.count("\n"), 25)

    def test_usage_error(self):
        r = subprocess.run([sys.executable, "-I", SCRIPT], capture_output=True, text=True)
        self.assertEqual(r.returncode, 2)


if __name__ == "__main__":
    unittest.main()
