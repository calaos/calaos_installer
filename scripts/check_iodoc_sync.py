#!/usr/bin/env python3
"""Fails when the documentation shipped in data/doc differs from calaos_base's.

    check_iodoc_sync.py <dir> [--data <data/doc>]
        <dir>: the io-doc artifact of calaos_base (en/, fr/)

The JSON files are compared parsed, so key order and formatting do not matter;
the order of an array does (calaos_base sorts the entries of io_doc.json by
name). io_doc.md is documentation, nothing reads it, and is not compared.
"""
import json
import os
import sys

LANGS = ("en", "fr")
FILES = ("io_doc.json", "device_templates.json")
MAX_REPORTED = 12


def diff(a, b, path, out):
    """Appends the differences between the shipped a and the server's b to out."""
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            if k not in b:
                out.append("%s.%s: shipped, but not generated by the server" % (path, k))
            elif k not in a:
                out.append("%s.%s: generated by the server, not shipped" % (path, k))
            else:
                diff(a[k], b[k], "%s.%s" % (path, k), out)
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) == len(b):
            for i, (x, y) in enumerate(zip(a, b)):
                diff(x, y, "%s[%s]" % (path, label(x, i)), out)
        else:
            ka = {label(x, i): x for i, x in enumerate(a)}
            kb = {label(y, i): y for i, y in enumerate(b)}
            for k in ka:
                if k not in kb:
                    out.append("%s[%s]: shipped, but not generated by the server" % (path, k))
            for k in kb:
                if k not in ka:
                    out.append("%s[%s]: generated by the server, not shipped" % (path, k))
            for k in ka:
                if k in kb:
                    diff(ka[k], kb[k], "%s[%s]" % (path, k), out)
    elif a != b:
        out.append("%s: shipped %s, server %s" % (path, short(a), short(b)))


def label(item, index):
    if isinstance(item, dict):
        for key in ("id", "name", "role"):
            if key in item:
                return item[key]
    return index


def short(v):
    s = json.dumps(v, ensure_ascii=False)
    return s if len(s) <= 60 else s[:57] + "..."


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main(argv):
    args = argv[1:]
    data = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "doc")
    if len(args) == 3 and args[1] == "--data":
        data = args[2]
        args = args[:1]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    ref = args[0]

    failed = False
    for lang in LANGS:
        for name in FILES:
            shipped, server = os.path.join(data, lang, name), os.path.join(ref, lang, name)
            for p in (shipped, server):
                if not os.path.isfile(p):
                    print("missing: %s" % p, file=sys.stderr)
                    failed = True
            if not (os.path.isfile(shipped) and os.path.isfile(server)):
                continue

            out = []
            diff(load(shipped), load(server), "%s/%s" % (lang, name), out)
            if out:
                failed = True
                print("%s/%s differs from calaos_base (%d differences):" % (lang, name, len(out)))
                for line in out[:MAX_REPORTED]:
                    print("  " + line)
                if len(out) > MAX_REPORTED:
                    print("  ... and %d more" % (len(out) - MAX_REPORTED))
            else:
                print("%s/%s: same as calaos_base" % (lang, name))

    if failed:
        print("\nRegenerate with ./generate_iodoc.sh and commit data/doc.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
